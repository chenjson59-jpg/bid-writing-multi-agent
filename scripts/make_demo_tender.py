_LEFT = 56
_FONT = "china-s"


def _body_rect(page) -> pymupdf.Rect:
    rect = page.rect
    return pymupdf.Rect(_LEFT, _LEFT, rect.width - _LEFT, rect.height - _LEFT)


def build(path: Path = OUTPUT) -> Path:
    """渲染 PDF 并写入书签，返回输出路径。"""
    doc = pymupdf.open()
    for index, (title, text) in enumerate(PAGES):
        page = doc.new_page()
        if index == 0:
            # 封面：居中大字
            page.insert_textbox(
                _body_rect(page), text, fontname=_FONT, fontsize=20,
                lineheight=2.2, align=pymupdf.TEXT_ALIGN_CENTER,
            )
            continue
        leftover = page.insert_textbox(
            _body_rect(page), text, fontname=_FONT, fontsize=11, lineheight=1.7,
        )
        if leftover < 0:
            raise RuntimeError(f"第 {index + 1} 页内容超出页面，请拆分：{title}")

    doc.set_toc(TOC)
    doc.set_metadata(
        {
            "title": f"{PROJECT_NAME} 招标文件（合成演示数据）",
            "author": "Demo Dataset",
            "subject": TENDER_NO,
            "keywords": "演示数据, 合成, 脱敏",
        }
    )

    path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(path, garbage=3, deflate=True)
    doc.close()
    return path


def main() -> None:
    out = build()
    print(f"已生成：{out}")
    with pymupdf.open(out) as doc:
        print(f"页数：{doc.page_count}")
        for level, title, page in doc.get_toc(simple=True):
            print(f"  书签 L{level} {title} → 第 {page} 页")


if __name__ == "__main__":
    main()
